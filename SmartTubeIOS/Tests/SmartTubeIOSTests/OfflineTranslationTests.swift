import AVFoundation
import Foundation
import Testing

@testable import SmartTubeIOS
@testable import SmartTubeIOSCore

// Shares the serialized owner of OfflineDecisionURLProtocol.log.
extension OfflinePlaybackDecisionTests {
    @Test("Translation language uses original speech, ignores dubs and normalizes regional codes")
    func translationLanguageEvidence() throws {
        let url = try #require(URL(string: "https://example.invalid/captions"))
        let original = VideoFormat(
            label: "Original", width: 0, height: 0, fps: 0, mimeType: "audio/mp4",
            audioLanguage: "EN_us", isOriginalAudio: true)
        let dubbed = VideoFormat(
            label: "Dubbed", width: 0, height: 0, fps: 0, mimeType: "audio/mp4",
            audioLanguage: "ru", isOriginalAudio: false)
        func source(_ formats: [VideoFormat], language: String, generated: Bool) -> String {
            PlayerInfo(
                video: video(), formats: formats, hlsURL: nil, dashURL: nil,
                captionTracks: [
                    CaptionTrack(
                        id: "captions", baseURL: url, name: language, languageCode: language,
                        isAutoGenerated: generated)
                ], trackingURLs: nil, endCards: []
            ).voiceOverSourceLanguage
        }
        #expect(source([dubbed, original], language: "ru", generated: true) == "en")
        #expect(source([dubbed], language: "FR-fr", generated: true) == "fr")
        #expect(source([dubbed], language: "ru", generated: false) == "auto")
        #expect(source([], language: "xx", generated: true) == "auto")
    }

    @Test(
        "Offline translation uses the original language even when duration is already known", arguments: [false, true])
    func downloadTranslationUsesOriginalLanguage(knownDuration: Bool) async throws {
        let (api, _) = api()
        let vot = OfflineVOTProbe([.finished])
        let resolver = OfflineSourceResolver(api: api, vot: vot)
        var saved = video()
        saved.duration = knownDuration ? 60 : nil
        let source = try await resolver.resolve(video: saved, track: .translation("ru"), attempt: UUID())
        #expect(source.track.kind == .translation)
        #expect(await vot.requests.map(\.sourceLanguage) == ["en"])
        #expect(await vot.uploads.isEmpty)
    }

    @Test("An offline translation refusal preserves the Yandex reason")
    func downloadTranslationPreservesFailure() async throws {
        let (api, _) = api()
        let resolver = OfflineSourceResolver(api: api, vot: OfflineVOTProbe([.failed]))
        do {
            _ = try await resolver.resolve(video: video(), track: .translation("ru"), attempt: UUID())
            Issue.record("Expected Yandex refusal")
        } catch {
            #expect(error.localizedDescription == "Fixture failure")
        }
        #expect(OfflineTranslationError(message: nil).errorDescription?.isEmpty == false)
        #expect(
            OfflineTranslationError(message: " \n").errorDescription
                == OfflineTranslationError(message: nil).errorDescription)
    }

    @Test("A local video's rejected auto language retries once with its original language", arguments: [false, true])
    func liveTranslationRetriesKnownLanguage(succeeds: Bool) async throws {
        let (api, _) = api()
        let url = try voiceFile()
        defer { try? FileManager.default.removeItem(at: url) }
        let vot = OfflineVOTProbe([.failed, succeeds ? .finished : .failed], audioURL: url)
        let controller = VoiceOverTranslationController(api: api, client: vot)
        let player = AVPlayer()
        var playbackChanges: [Bool] = []
        defer { controller.stop() }
        controller.start(
            .init(
                videoId: "online-id", duration: 60, sourceLanguage: "auto", targetLanguage: "ru",
                livelyVoiceToken: nil, originalAudioURL: nil, originalAudioHLSURL: nil,
                originalAudioUserAgent: InnerTubeClients.VisionOS.userAgent, isOfflineVideo: true),
            mainPlayer: player, setVideoPlaying: { playbackChanges.append($0) })
        #expect(
            await eventually {
                switch controller.state {
                case .playing, .failed: true
                default: false
                }
            })
        #expect(await vot.requests.map(\.sourceLanguage) == ["auto", "en"])
        #expect(OfflineDecisionURLProtocol.log.count == 2)
        #expect(await vot.uploads.isEmpty)
        #expect(playbackChanges == [false, true])
        #expect(controller.state == (succeeds ? .playing(livelyVoice: false) : .failed("Fixture failure")))
    }
}
