import Foundation
import SmartTubeIOSCore

// MARK: - Default audio language → original / dubbed track / Yandex voice-over

extension PlaybackViewModel {

    /// Runs once the audio tracks of the current item are known. AudioTrackManager has already
    /// selected an original or dubbed track in `preferredAudioLanguage` when one exists; if the
    /// video has none and Yandex VOT is enabled, it is voice-over translated into that language.
    /// The player's per-video toggle (`voiceOverOverride`) overrides both checks.
    func applyAudioLanguagePolicy() {
        let forced = voiceOverOverride == true
        guard voiceOverOverride ?? settings.yandexVOTEnabled, let video = currentVideo, let info = playerInfo,
            let target = voiceOverTargetLanguage
        else { return }

        let tracks = audioManager.availableAudioTracks
        // Original language: the creator's track, else the auto-generated captions' language.
        // VISIONOS masters carry no LANGUAGE, so their only track reads "unknown".
        let original =
            tracks.first(where: \.isOriginal).map(\.languageCode).flatMap { $0 == "unknown" ? nil : $0 }
            ?? info.captionTracks.first(where: \.isAutoGenerated)?.languageCode
        let source = original.map(Self.baseLanguage)
        if forced {
            // Yandex translates the original, so play it (ducked) instead of a dub.
            if let originalTrack = tracks.first(where: \.isOriginal), selectedAudioTrack?.id != originalTrack.id {
                selectAudioTrack(originalTrack)
            }
        } else {
            if tracks.contains(where: { Self.baseLanguage($0.languageCode) == target }) { return }
            if source == target { return }
        }

        let videoDuration = duration > 0 ? duration : (info.video.duration ?? 0)
        guard videoDuration <= YandexVOTClient.maximumDuration else { return }
        let audioFormat = info.formats
            .filter { $0.mimeType.hasPrefix("audio/") && $0.url != nil }
            .min { ($0.bitrate ?? .max) < ($1.bitrate ?? .max) }
        let audioURL = audioFormat?.url
        let livelyToken = settings.yandexVOTLivelyVoice && target == "ru" ? TokenManager.yandexVOTToken() : nil

        voiceOver.keepsOriginalAudio = settings.yandexVOTKeepOriginalAudio
        voiceOver.start(
            .init(
                videoId: video.id,
                duration: videoDuration,
                sourceLanguage: source.flatMap { YandexVOTClient.sourceLanguages.contains($0) ? $0 : nil } ?? "auto",
                targetLanguage: target,
                livelyVoiceToken: livelyToken,
                originalAudioURL: audioURL,
                originalAudioHLSURL: info.hlsURL,
                originalAudioUserAgent: info.isFromVisionOSClient
                    ? InnerTubeClients.VisionOS.userAgent : InnerTubeClients.iOS.userAgent
            ),
            mainPlayer: player,
            setVideoPlaying: { [weak self] playing in self?.setPlayingForVoiceOver(playing) }
        )
    }

    /// The default audio language when Yandex can translate into it (ru, en, kk), else `nil`.
    var voiceOverTargetLanguage: String? {
        settings.preferredAudioLanguage.map(Self.baseLanguage)
            .flatMap { YandexVOTClient.targetLanguages.contains($0) ? $0 : nil }
    }

    /// Holds or resumes the video while Yandex prepares the translation, keeping `isPlaying` in
    /// sync so the rate observer doesn't treat the hold as a stall.
    func setPlayingForVoiceOver(_ playing: Bool) {
        if playing, !canResumeInAudioSession { return }
        if !playing { cancelPendingAudioPlayback() }
        if !playing { cancelBackgroundQualityUpgrade() }
        isPlaying = playing
        if !playing { cancelStallRecovery() }
        if playing { player.rate = Float(settings.playbackSpeed) } else { player.pause() }
        #if canImport(UIKit)
        updateNowPlayingPlayback()
        #endif
    }

    /// Whether this video is being translated (or waiting for Yandex) right now.
    var isVoiceOverActive: Bool {
        guard voiceOver.videoId == currentVideo?.id else { return false }
        switch voiceOver.state {
        case .waiting, .playing: return true
        case .idle, .failed: return false
        }
    }

    /// The player's "Translate This Video" toggle.
    func setVoiceOverForCurrentVideo(_ enabled: Bool) {
        voiceOverOverride = enabled
        restartVoiceOver()
    }

    /// Applies the player's translation toggles to the current video right away.
    func restartVoiceOver() {
        voiceOver.cancelAndResume()
        applyAudioLanguagePolicy()
    }

    private static func baseLanguage(_ code: String) -> String {
        String(code.lowercased().prefix { $0 != "-" && $0 != "_" })
    }
}

extension PlayerInfo {
    /// Stream URLs from the VISIONOS client carry `c=VISIONOS`; they need its UA and HLS policy.
    var isFromVisionOSClient: Bool {
        formats.contains { $0.url?.query?.contains("c=VISIONOS") == true }
    }
}
